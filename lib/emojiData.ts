/** 검색할 때 쓰는 납작한 목록. 그룹을 가로질러 한 번에 훑는다. */
export const ALL_EMOJIS: EmojiItem[] = EMOJI_GROUPS.flatMap((g) => g.items);

/**
 * 검색어에 맞는 이모지. 빈 검색어면 null을 돌려준다 —
 * '전부 보여주기'와 '찾은 게 없음'을 화면이 구분해야 해서 빈 배열을 쓰지 않는다.
 */
export function searchEmojis(query: string): EmojiItem[] | null {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  // 이모지 자체를 붙여넣어 찾는 경우도 받아준다.
  return ALL_EMOJIS.filter((it) => it.k.includes(q) || it.e === q);
}
